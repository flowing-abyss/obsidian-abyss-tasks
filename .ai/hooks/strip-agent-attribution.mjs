#!/usr/bin/env node

// git commit-msg hook (run from .husky/commit-msg): removes the credit coding
// agents add to their commit messages, so none of it reaches the history or
// shows up as a co-author on GitHub. Cleans the message instead of rejecting
// the commit — a rejected commit only sends an agent into a rewrite loop or
// past the hooks with --no-verify.
//
// Runs on the final message file, so it works the same for every agent and
// for commits made by hand, however the message was written (-m, -F, a
// heredoc, the editor, --amend).
//
// What gets removed:
// - every `Co-authored-by:` trailer, in any letter case. Agents all use this
//   one trailer and differ only in name and address (vendor domains, [bot]
//   accounts, made-up ones like roo@code.local), so no list of agents can be
//   complete. A human co-author's trailer goes too.
// - "Generated with <agent>" footers: any that start with an emoji, or that
//   name a known agent — a plain "Generated by `pnpm run build`" stays.
// - session-link trailers (Claude Code's `Claude-Session:`, Amp's
//   `Amp-Thread-ID:`).
//
// `--check <revision-range>` is CI's backstop for commits that skipped the
// hook (--no-verify, commits made through the GitHub API): it changes
// nothing and fails, naming each commit in the range that carries any of it.

import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import process from 'node:process';

const CO_AUTHOR_TRAILER = /^\s*co-authored-by\s*:/i;
const SESSION_TRAILER = /^\s*(?:claude-session|amp-thread-id|amp-thread)\s*:/i;
const GENERATED_FOOTER = /^\s*(\p{Extended_Pictographic}\uFE0F?)?\s*generated (?:with|by)\b(.*)$/iu;
const AGENT_NAME =
  /\b(?:claude|codex|opencode|crush|cursor|copilot|amp|aider|gemini|jules|devin|droid|warp|qwen|kiro|kilo|augment|windsurf|cascade|goose|roo|cline|junie)\b/i;
// `git commit -v` appends the diff below this line; git drops it later, and
// nothing in it is part of the message.
const SCISSORS = /^\S* -{24} >8 -{24}$/;

const [target, range] = process.argv.slice(2);
if (target === '--check' && range) {
  process.exit(checkRange(range));
}
if (!target || target === '--check') {
  process.stderr.write(
    'usage: strip-agent-attribution.mjs <commit-message-file>\n' +
      '       strip-agent-attribution.mjs --check <revision-range>\n',
  );
  process.exit(2);
}
stripMessageFile(target);

function stripMessageFile(messageFile) {
  // An editor on Windows may save the message with CRLF; a cleaned message is
  // written back with LF, which is how git stores it anyway.
  const lines = readFileSync(messageFile, 'utf8').split(/\r?\n/);
  const scissorsAt = lines.findIndex((line) => SCISSORS.test(line));
  const messageLines = scissorsAt === -1 ? lines : lines.slice(0, scissorsAt);
  const rest = scissorsAt === -1 ? [] : lines.slice(scissorsAt);

  const kept = messageLines.filter((line) => !isAttribution(line));
  const removed = messageLines.length - kept.length;
  if (removed === 0) {
    return;
  }

  const message = `${collapseBlankLines(kept).join('\n').trimEnd()}\n`;
  writeFileSync(messageFile, message + rest.join('\n'));
  process.stderr.write(
    `strip-agent-attribution: removed ${removed} agent attribution line(s) from the commit message.\n`,
  );
}

/** The exit code for a commit range: 0 when every message is clean, 1 when not. */
function checkRange(revisionRange) {
  const log = spawnSync('git', ['log', '--format=%h %s%x00%B%x1e', revisionRange], {
    encoding: 'utf8',
  });
  if (log.status !== 0) {
    process.stderr.write(
      log.stderr || `strip-agent-attribution: git log ${revisionRange} failed\n`,
    );
    return 2;
  }

  const offenders = log.stdout.split('\x1e').flatMap((record) => {
    const [commit, message = ''] = record.replace(/^\n/, '').split('\0');
    const lines = message.split(/\r?\n/).filter(isAttribution);
    return commit && lines.length > 0 ? [{ commit, lines }] : [];
  });
  if (offenders.length === 0) {
    return 0;
  }

  process.stderr.write(
    `strip-agent-attribution: ${offenders.length} commit(s) carry agent attribution lines:\n`,
  );
  for (const { commit, lines } of offenders) {
    process.stderr.write(`\n  ${commit}\n${lines.map((line) => `    ${line.trim()}\n`).join('')}`);
  }
  process.stderr.write(
    '\nRemove these lines from the commit messages (for example with `git rebase -i` and ' +
      '`reword`), then force-push the branch.\n',
  );
  return 1;
}

function isAttribution(line) {
  if (CO_AUTHOR_TRAILER.test(line) || SESSION_TRAILER.test(line)) {
    return true;
  }
  const footer = line.match(GENERATED_FOOTER);
  return Boolean(footer && (footer[1] || AGENT_NAME.test(footer[2])));
}

/** Removing a line can leave two blank lines in a row; keep one, as git's cleanup would. */
function collapseBlankLines(input) {
  return input.filter((line, index) => line.trim() || input[index - 1]?.trim());
}
